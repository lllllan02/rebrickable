/** 按 color_id 取中文色名；无映射时返回 null */
export function catalogColorNameZh(colorId: number): string | null {
  const zh = COLOR_NAME_ZH[colorId];
  return zh ?? null;
}

/** 目录色名双语：`中文 · English`（与高砖色名展示一致） */
export function formatCatalogBilingualColorLabel(
  colorId: number,
  colorNameEn?: string | null
): string {
  return formatGobricksBilingualColorLabel({
    nameZh: catalogColorNameZh(colorId),
    nameEn: colorNameEn,
    catalogColorName: colorNameEn,
  });
}
